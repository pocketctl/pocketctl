import {JobDeferredError} from '../jobs/types.js'
import { sourcePoolContext } from './pool-context.js'

export type ProjectionStage = 'read_seal' | 'select_page' | 'checkout' | 'begin' | 'verify_version'
  | 'write_references' | 'checkpoint' | 'complete_watermark' | 'commit' | 'ack'

interface FailureFields {
  projection_stage: ProjectionStage
  projection_stage_ms: number
  projection_page_size?: number
  projection_commit_sent?: boolean
  projection_rollback_confirmed?: boolean
  projection_historical?: boolean
  projection_rows_processed?: number
  projection_revision_changed?: boolean
  projection_reason?: 'lock_conflict' | 'authority_or_version_changed'
}

const failures = new WeakMap<object, FailureFields>()

/** Keep the first failing boundary across nested calls. Only metadata generated by this process is retained. */
export function projectionErrorFields(error: unknown): Partial<FailureFields> {
  return error && typeof error === 'object' ? {...failures.get(error)} : {}
}

/** The writer raises this only when the installation mutex explicitly returns false. */
export class ProjectionLockBusy extends Error {
  rollbackConfirmed = false
  constructor() { super('canonical_reference_busy') }
  defer(availableAt: Date) {
    const wait = new JobDeferredError('source_not_ready', availableAt)
    const fields = failures.get(this)
    if (fields) failures.set(wait, {...fields, projection_reason: 'lock_conflict'})
    return wait
  }
}

export function recordProjectionRollback(error:unknown):void {
  const fields=error && typeof error==='object' ? failures.get(error) : undefined
  if(fields)fields.projection_rollback_confirmed=true
}

export class ProjectionTiming {
  private started = performance.now()
  rowsProcessed = 0
  revisionChanged?: boolean
  constructor(private readonly pool: object, private stage: ProjectionStage,
    private readonly page?: {size: number; historical: boolean}) {}

  private observe(): number {
    const ms = performance.now() - this.started
    sourcePoolContext(this.pool).observeDuration?.(`projection_${this.stage}`, ms)
    return Math.max(0, Math.round(ms))
  }

  enter(stage: ProjectionStage) {
    this.observe()
    this.stage = stage
    this.started = performance.now()
  }

  finish() { this.observe() }

  failure(error: unknown, commitSent?: boolean, reason?: FailureFields['projection_reason']) {
    const ms = this.observe()
    if (error && typeof error === 'object' && !failures.has(error)) {
      failures.set(error, {projection_stage: this.stage, projection_stage_ms: ms,
        ...(this.page && {projection_page_size: this.page.size, projection_historical: this.page.historical, projection_rows_processed: this.rowsProcessed}),
        ...(this.revisionChanged !== undefined && {projection_revision_changed: this.revisionChanged}),
        ...(reason && {projection_reason: reason}),
        ...(commitSent !== undefined && {projection_commit_sent: commitSent})})
    }
    return error
  }
}

export async function observeProjectionStep<T>(pool: object, stage: ProjectionStage, work: () => Promise<T>, page?: {size:number;historical:boolean}): Promise<T> {
  const timing = new ProjectionTiming(pool, stage, page)
  try {
    const result = await work()
    timing.finish()
    return result
  } catch (error) {
    throw timing.failure(error)
  }
}

/** An explicit SQL denial settles COMMIT. Socket errors and connection-class
 * server responses leave the durable checkpoint as the only outcome witness. */
export function commitOutcomeUnknown(error: unknown): boolean {
  const code = error && typeof error === 'object' && 'code' in error ? error.code : undefined
  return typeof code !== 'string' || !/^(?:[0-9]{2}|[0-9][A-Z]|F0|HV|P0|XX)[A-Z0-9]{3}$/.test(code)
    || code === '40003' || code.startsWith('08') || code.startsWith('57')
}
