import { mount, flushPromises } from '@vue/test-utils'
import { beforeEach, expect, test, vi } from 'vitest'
const api=vi.hoisted(()=>({listContextSettings:vi.fn(),putContextSetting:vi.fn(),listContextPacks:vi.fn(),submitContextFeedback:vi.fn()}))
vi.mock('../../services/memoryClient',()=>api)
vi.mock('../../composables/useLocale',()=>({useLocale:()=>({t:(key:string)=>key})}))
import MemoryContextWorkspace from './MemoryContextWorkspace.vue'
beforeEach(()=>{vi.resetAllMocks();api.listContextSettings.mockResolvedValue({settings:[]});api.listContextPacks.mockResolvedValue({packs:[{pack_id:'one',state:'ready',client_request_id:'request',created_at:'2026-11-06',stable_text:'whole content',items:[],trajectory:null,delivery:null}]})})
test('switching context sections offers keep or discard and retains config component',async()=>{
 const wrapper=mount(MemoryContextWorkspace,{attachTo:document.body});await flushPromises()
 await wrapper.get('[data-testid="context-settings-add"]').trigger('click')
 await wrapper.get('[data-testid="context-tokens"]').setValue('1500')
 await wrapper.findAll('[role="tab"]')[1]!.trigger('click')
 expect(wrapper.find('[data-testid="context-draft-prompt"]').exists()).toBe(true)
 await wrapper.get('[data-testid="context-draft-keep"]').trigger('click')
 expect(wrapper.get('[data-testid="memory-context-settings"]').isVisible()).toBe(false)
 await wrapper.findAll('[role="tab"]')[0]!.trigger('click')
 expect(wrapper.get<HTMLInputElement>('[data-testid="context-tokens"]').element.value).toBe('1500')
 await wrapper.findAll('[role="tab"]')[1]!.trigger('click');await wrapper.get('[data-testid="context-draft-discard"]').trigger('click')
 await wrapper.findAll('[role="tab"]')[0]!.trigger('click')
 expect(wrapper.find('[data-testid="context-settings-form"]').exists()).toBe(false)
 expect(api.putContextSetting).not.toHaveBeenCalled()
})
test('pack selection has a return action and changing session clears detail',async()=>{
 const wrapper=mount(MemoryContextWorkspace,{attachTo:document.body});await flushPromises()
 await wrapper.findAll('[role="tab"]')[1]!.trigger('click')
 await wrapper.get('[data-testid="pack-session-input"]').setValue('session-one')
 await wrapper.get('[data-testid="pack-refresh"]').trigger('click');await flushPromises()
 await wrapper.get('[data-testid="pack-select-one"]').trigger('click')
 expect(wrapper.get('[data-testid="detail-stable"]').text()).toBe('whole content')
 await wrapper.get('[data-testid="context-pack-back"]').trigger('click')
 expect(wrapper.find('[data-testid="context-pack-detail"]').exists()).toBe(true)
 await wrapper.get('[data-testid="pack-session-input"]').setValue('session-two')
 expect(wrapper.find('[data-testid="context-pack-detail"]').exists()).toBe(false)
})

test('feedback belongs to selected pack detail and retains selected pack identity',async()=>{
 api.submitContextFeedback.mockResolvedValue({})
 const wrapper=mount(MemoryContextWorkspace);await flushPromises()
 await wrapper.findAll('[role="tab"]')[1]!.trigger('click')
 await wrapper.get('[data-testid="pack-session-input"]').setValue('session')
 await wrapper.get('[data-testid="pack-refresh"]').trigger('click');await flushPromises()
 expect(wrapper.find('[data-testid="feedback-used"]').exists()).toBe(false)
 await wrapper.get('[data-testid="pack-select-one"]').trigger('click')
 await wrapper.get('[data-testid="feedback-used"]').trigger('click');await flushPromises()
 expect(api.submitContextFeedback).toHaveBeenCalledExactlyOnceWith({packId:'one',action:'used'})
 expect(wrapper.get('[data-testid="pack-feedback-status"]').text()).toContain('memory.ui.context.feedbackRecorded')
 wrapper.unmount()
})

test('feedback result for a previous selection never appears under another pack',async()=>{
 let finish!:(value:unknown)=>void
 api.submitContextFeedback.mockImplementationOnce(()=>new Promise(r=>finish=r))
 api.listContextPacks.mockResolvedValue({packs:[{pack_id:'one',state:'ready',client_request_id:'request',created_at:'2026-11-06',items:[]},{pack_id:'two',state:'ready',client_request_id:'request-two',created_at:'2026-11-06',items:[]}]})
 const wrapper=mount(MemoryContextWorkspace);await flushPromises()
 await wrapper.findAll('[role="tab"]')[1]!.trigger('click')
 await wrapper.get('[data-testid="pack-session-input"]').setValue('session')
 await wrapper.get('[data-testid="pack-refresh"]').trigger('click');await flushPromises()
 await wrapper.get('[data-testid="pack-select-one"]').trigger('click')
 await wrapper.get('[data-testid="feedback-used"]').trigger('click')
 await wrapper.get('[data-testid="pack-select-two"]').trigger('click')
 finish({});await flushPromises()
 expect(wrapper.find('[data-testid="pack-feedback-status"]').exists()).toBe(false)
 wrapper.unmount()
})
