import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, expect, test, vi } from 'vitest'
vi.mock('../../composables/useLocale', () => ({ useLocale: () => ({ t: (key: string) => key }) }))
const read = vi.hoisted(() => vi.fn())
vi.mock('../../services/memoryOperationalStatus', () => ({ readMemoryOperationalStatus: read }))
import MemoryOperationalStatus from './MemoryOperationalStatus.vue'
beforeEach(() => { vi.useFakeTimers(); read.mockReset() })
afterEach(() => vi.useRealTimers())
test('degraded feed shows actionable reason then clears after recovery', async () => {
  read.mockResolvedValueOnce({state:'degraded',last_error_code:'feed_stalled'})
    .mockResolvedValueOnce({state:'ready',last_error_code:null})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises()
  expect(wrapper.attributes('role')).toBe('alert')
  expect(wrapper.text()).toContain('memory.operational.feed_stalled')
  await vi.advanceTimersByTimeAsync(60000); await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.ready')
  expect(wrapper.text()).not.toContain('memory.operational.feed_stalled')
  wrapper.unmount()
})
test('failed refresh replaces stale ready with unknown rather than claiming healthy', async () => {
  read.mockResolvedValueOnce({state:'ready',last_error_code:null}).mockRejectedValueOnce(Error('private server details'))
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises(); await vi.advanceTimersByTimeAsync(60000); await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.unknown')
  expect(wrapper.text()).not.toContain('private server details')
  expect(wrapper.text()).not.toContain('memory.operational.ready')
  wrapper.unmount()
})
test('budget block is distinguished from service enablement and arbitrary error strings are hidden', async () => {
  read.mockResolvedValue({state:'degraded',last_error_code:'budget_blocked'})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises(); expect(wrapper.text()).toContain('memory.operational.budget_blocked')
  read.mockResolvedValue({state:'degraded',last_error_code:'sensitive-arbitrary-value'})
  await vi.advanceTimersByTimeAsync(60000);await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.degraded')
  expect(wrapper.text()).not.toContain('sensitive-arbitrary-value')
  wrapper.unmount()
})
test('a pending refresh stops displaying stale ready immediately', async () => {
  read.mockResolvedValueOnce({state:'ready',last_error_code:null}).mockImplementationOnce(()=>new Promise(()=>{}))
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises();expect(wrapper.text()).toContain('memory.operational.ready')
  await vi.advanceTimersByTimeAsync(60000);await flushPromises()
  expect(wrapper.text()).not.toContain('memory.operational.ready')
  wrapper.unmount()
})
test('a timed out poll shows unknown and releases refresh for recovery', async () => {
  read.mockResolvedValueOnce({state:'ready',last_error_code:null})
    .mockImplementationOnce(()=>new Promise((_resolve,reject)=>setTimeout(()=>reject(Error('memory_status_unavailable')),10000)))
    .mockResolvedValueOnce({state:'ready',last_error_code:null})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises();await vi.advanceTimersByTimeAsync(60000);await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.loading')
  await vi.advanceTimersByTimeAsync(10000);await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.unknown')
  expect(wrapper.get('button').attributes('disabled')).toBeUndefined()
  await wrapper.get('button').trigger('click');await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.ready')
  wrapper.unmount()
})
