import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, expect, test, vi } from 'vitest'
vi.mock('../../composables/useLocale', () => ({ useLocale: () => ({ t: (key: string) => key }) }))
const read = vi.hoisted(() => vi.fn())
vi.mock('./MemoryExtractionIssues.vue',()=>({default:{template:'<section data-testid="recovery-content">recovery actions</section>'}}))
vi.mock('../../services/memoryOperationalStatus', () => ({ readMemoryOperationalStatus: read }))
import MemoryOperationalStatus from './MemoryOperationalStatus.vue'
beforeEach(() => { vi.useFakeTimers(); read.mockReset() })
afterEach(() => {vi.useRealTimers();document.body.replaceChildren()})
async function openDetails(wrapper:ReturnType<typeof mount>){await wrapper.get('[data-testid="memory-operational-trigger"]').trigger('click');await flushPromises();return document.querySelector('dialog')!}
test('degraded feed shows actionable reason then clears after recovery', async () => {
  read.mockResolvedValueOnce({state:'degraded',last_error_code:'feed_stalled'})
    .mockResolvedValueOnce({state:'ready',last_error_code:null})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises()
  expect(wrapper.attributes('role')).toBe('alert')
  expect(wrapper.text()).not.toContain('memory.operational.feed_stalled')
  expect((await openDetails(wrapper)).textContent).toContain('memory.operational.feed_stalled')
  await vi.advanceTimersByTimeAsync(60000); await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.ready')
  expect(wrapper.text()).not.toContain('memory.operational.feed_stalled')
  wrapper.unmount()
})
test('failed refresh replaces stale ready with unknown rather than claiming healthy', async () => {
  read.mockResolvedValueOnce({state:'ready',last_error_code:null}).mockRejectedValueOnce(Error('private server details'))
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises(); await vi.advanceTimersByTimeAsync(60000); await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.unknown')
  expect(wrapper.text()).not.toContain('private server details')
  expect(wrapper.text()).not.toContain('memory.operational.ready')
  wrapper.unmount()
})
test('budget block is distinguished from service enablement and arbitrary error strings are hidden', async () => {
  read.mockResolvedValue({state:'degraded',last_error_code:'budget_blocked'})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises(); expect((await openDetails(wrapper)).textContent).toContain('memory.operational.budget_blocked')
  read.mockResolvedValue({state:'degraded',last_error_code:'sensitive-arbitrary-value'})
  await vi.advanceTimersByTimeAsync(60000);await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.degraded')
  expect(wrapper.text()).not.toContain('sensitive-arbitrary-value')
  wrapper.unmount()
})
test('a pending refresh stops displaying stale ready immediately', async () => {
  read.mockResolvedValueOnce({state:'ready',last_error_code:null}).mockImplementationOnce(()=>new Promise(()=>{}))
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises();expect(wrapper.text()).toContain('memory.operational.ready')
  await vi.advanceTimersByTimeAsync(60000);await flushPromises()
  expect(wrapper.text()).not.toContain('memory.operational.ready')
  wrapper.unmount()
})
test('a timed out poll shows unknown and releases refresh for recovery', async () => {
  read.mockResolvedValueOnce({state:'ready',last_error_code:null})
    .mockImplementationOnce(()=>new Promise((_resolve,reject)=>setTimeout(()=>reject(Error('memory_status_unavailable')),10000)))
    .mockResolvedValueOnce({state:'ready',last_error_code:null})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises();await vi.advanceTimersByTimeAsync(60000);await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.loading')
  await vi.advanceTimersByTimeAsync(10000);await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.unknown')
  expect(wrapper.get('button').attributes('disabled')).toBeUndefined()
  await openDetails(wrapper)
  document.querySelector<HTMLButtonElement>('[data-testid="memory-operational-refresh"]')!.click();await flushPromises()
  expect(wrapper.text()).toContain('memory.operational.ready')
  wrapper.unmount()
})
test('unresolved extraction failure shows its actionable reason and supports refresh', async () => {
  read.mockResolvedValueOnce({state:'degraded',last_error_code:'extraction_failed'})
    .mockResolvedValueOnce({state:'ready',last_error_code:null})
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
  await flushPromises()
  expect(wrapper.attributes('role')).toBe('alert')
  expect((await openDetails(wrapper)).textContent).toContain('memory.operational.extraction_failed')
  expect(wrapper.get('button').attributes('disabled')).toBeUndefined()
  await openDetails(wrapper)
  document.querySelector<HTMLButtonElement>('[data-testid="memory-operational-refresh"]')!.click();await flushPromises()
  expect(wrapper.text()).not.toContain('memory.operational.extraction_failed')
  expect(wrapper.attributes('role')).toBe('status')
  wrapper.unmount()
})

test('global notice opens a body modal and never expands actions into the header',async()=>{
 read.mockResolvedValue({state:'degraded',last_error_code:'extraction_failed'})
 const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'},attachTo:document.body})
 await flushPromises()
 const trigger=wrapper.get<HTMLButtonElement>('[data-testid="memory-operational-trigger"]')
 trigger.element.focus()
 const dialog=await openDetails(wrapper)
 expect((dialog as HTMLDialogElement).open).toBe(true)
 expect(dialog.parentElement).toBe(document.body)
 expect(dialog.querySelector('[data-testid="recovery-content"]')).not.toBeNull()
 expect(wrapper.find('[data-testid="recovery-content"]').exists()).toBe(false)
 dialog.dispatchEvent(new Event('cancel',{cancelable:true}));await flushPromises()
 expect(document.querySelector('dialog')).toBeNull()
 expect(document.activeElement).toBe(trigger.element)
 wrapper.unmount()
})
test('changing installations closes the modal and removes old details',async()=>{
 read.mockResolvedValue({state:'degraded',last_error_code:'extraction_failed'})
 const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'}})
 await flushPromises();await openDetails(wrapper)
 await wrapper.setProps({installationId:'two'});await flushPromises()
 expect(document.querySelector('dialog')).toBeNull();wrapper.unmount()
})

test('unresolved warning stays visible during refresh until confirmed recovery', async () => {
  let resolveRead!: (value: unknown) => void
  read.mockResolvedValueOnce({state:'degraded',last_error_code:'extraction_failed'})
    .mockImplementationOnce(()=>new Promise(resolve=>{resolveRead=resolve}))
  const wrapper=mount(MemoryOperationalStatus,{props:{installationId:'one'},attachTo:document.body})
  await flushPromises();await vi.advanceTimersByTimeAsync(60000)
  expect(wrapper.isVisible()).toBe(true)
  expect(wrapper.attributes('role')).toBe('alert')
  expect((await openDetails(wrapper)).textContent).toContain('memory.operational.extraction_failed')
  resolveRead({state:'ready',last_error_code:null});await flushPromises()
  expect(document.querySelector('dialog')!.textContent).toContain('memory.operational.ready')
  document.querySelector('dialog')!.dispatchEvent(new Event('cancel',{cancelable:true}));await flushPromises()
  expect(wrapper.isVisible()).toBe(false)
  wrapper.unmount()
})
