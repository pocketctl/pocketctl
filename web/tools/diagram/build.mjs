// From this directory run npm ci, then npm run build. Both clients ship the same output.
import { readFile, writeFile } from 'node:fs/promises';

const file = (path) => new URL(path, import.meta.url);
const upstream = 'node_modules/@mermaid-js/tiny/';
const [bundle, license, adapter] = await Promise.all([
  readFile(file(upstream + 'dist/mermaid.tiny.js'), 'utf8'),
  readFile(file(upstream + 'LICENSE'), 'utf8'),
  readFile(file('adapter.js'), 'utf8'),
]);
// Keep Mermaid private so its automatic discovery and API cannot affect the host.
const exportLine = 'globalThis["mermaid"] = globalThis.__esbuild_esm_mermaid_nm["mermaid"].default;';
if (!bundle.trimEnd().endsWith(exportLine)) throw new Error('Unexpected Mermaid distribution');
const engine = bundle.slice(0, bundle.lastIndexOf(exportLine));
await writeFile(file('../../public/diagram/runtime.js'), [
  '/*! Generated by web/tools/diagram/build.mjs. Mermaid Tiny 12.3.0.',
  license.trimEnd(), '*/', '(function () {', engine,
  'const mermaid = __esbuild_esm_mermaid_nm.mermaid.default;', adapter, '})();', '',
].join('\n'));
